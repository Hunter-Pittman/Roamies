import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
// Exercise the real canvas bubble: approval text must scroll instead of being a clipped placeholder.
const drawn=[];
const context=new Proxy({fillText:(text)=>drawn.push(text),measureText:text=>({width:String(text).length*8})},{get:(target,key)=>key in target?target[key]:()=>{}});
const document={createElement:()=>({width:0,height:0,getContext:()=>context})};
const glass=new Proxy({MONO:'monospace',CHIP_H:26,chipW:text=>String(text).length*8+18,textW:text=>String(text).length*8},{get:(target,key)=>key in target?target[key]:()=>{}});
const clamp=(v,a,b)=>Math.max(a,Math.min(b,v));
const R={clamp,lerp:(a,b,t)=>a+(b-a)*t,damp:(a,b,k,dt)=>a+(b-a)*(1-Math.exp(-k*dt)),safe:{top:0,left:0,right:0,bottom:0},glass};
const window={Roamie:R};
vm.runInNewContext(fs.readFileSync(new URL('../../../roamies/agent.js',import.meta.url),'utf8'),{window,document,Math,Map,Promise,URLSearchParams});
const k={m:{x:500,y:500,radius:70,goTo(){},mode:'rest'},face:{set(){}},PAL:Array.from({length:6},()=>[0,200,180]),L:5,R:70,P:5,S(){},sq:{kick(){}},presence:'shown'};
const plugin=R.agentPlugin(k),api=plugin.api;
const review='BEGIN-REVIEW\n'+Array.from({length:80},(_,i)=>`Command ${i}: node server-${i}.mjs`).join('\n')+'\nEND-REVIEW';
let chosen=null;
const handle=api.prompt({placeholder:'Enable plugin?',review,choices:['Allow',"Don't allow"],onChoose:i=>{chosen=i;}});
const env={w:1280,h:900,dpr:1,mouse:{x:100,y:100,active:false},safe:R.safe};
const frames=(n=120)=>{for(let i=0;i<n;i++)plugin.update(1/60,env);};
frames();
assert.equal(api.bubble.text,review);assert.ok(api.bubble.overflow);assert.equal(api.bubble.scrollTarget,0,'approval starts at the beginning');
plugin.over(context,env);assert.ok(drawn.join('').includes('BEGIN-REVIEW'));assert.ok(!drawn.join('').includes('END-REVIEW'));
drawn.length=0;handle.scroll(100000);frames();plugin.over(context,env);assert.ok(drawn.join('').includes('END-REVIEW'),'last command/end marker is painted after keyboard scrolling');
assert.ok(api.bubble.input.choices.rects.length===2,'the existing approval buttons stay available');
const [x,y,w,h]=api.bubble.input.choices.rects[0];plugin.press(x+w/2,y+h/2);assert.equal(chosen,0,'Allow retains its actual user callback');
handle.scroll(-100000);frames();assert.equal(api.bubble.scrollTarget,0);plugin.wheel(400);frames();assert.ok(api.bubble.scroll.x>0,'mouse wheel scrolls review text');
frames(900);assert.ok(api.bubble,'approval does not expire while reading');
handle.close();
const ordinary=api.prompt({placeholder:'Ordinary question',choices:['Allow','Decline']});
assert.equal(api.bubble.text,'');assert.equal(api.bubble.input.review,undefined,'ordinary confirmation remains a placeholder');ordinary.close();
const secret=api.prompt({placeholder:'Token',mask:true});secret.set('fixture-secret');
assert.equal(api.bubble.text,'•'.repeat(14));assert.equal(api.bubble.input.review,undefined);assert.equal(api.bubble.input.choices,undefined);secret.close();
const text=api.prompt({placeholder:'Ordinary text'});text.set('normal reply');assert.equal(api.bubble.text,'normal reply');assert.equal(api.bubble.input.mask,false);text.close();
console.log('Actual canvas approval review paints first/last commands, scrolls, keeps buttons and never auto-dismisses: passed');
