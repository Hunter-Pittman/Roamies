// Saved model supervisors and read-only Task watches, independent of the conversation's turn limits.
import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import { randomUUID, createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { z } from 'zod';
import { writeJson } from './store.mjs';
import { interruptionRules, supervisorInterruption } from './interruptions.mjs';
import { checkRead, checkSupervisorStorage, BLOCK, orcaReadArgs, orcaSupervisorArgs } from './safety.mjs';

export const supervisorsRoot = () => path.join(process.env.ROAMIES_DATA_DIR ?? os.homedir(), 'Roamies', 'Supervisors');
const clip = (s, n = 1000) => String(s ?? '').slice(0, n);
const ID = /^s_[a-f0-9-]{36}$/;
const requestSchema = z.discriminatedUnion('action', [
  z.object({ action: z.enum(['hello', 'close']) }).strict(),
  // The overlay is a read-only projection. Only Roamie's model tools can create or control supervisors.
  z.object({ action: z.enum(['read', 'presented']), id: z.string().regex(ID) }).strict(),
  z.object({ action: z.literal('notified'), id: z.string().regex(ID), key: z.string().min(1).max(200) }).strict(),
]);
export const parseSupervisorRequest = (request) => requestSchema.parse(request);
const coordinatorReport = z.object({
  supervisorId: z.string().regex(ID), revision: z.number().int().min(1),
  state: z.enum(['working', 'waiting', 'paused', 'stopped', 'completed', 'failed']), progress: z.string().max(2000),
  report: z.string().max(20000).optional(), needsYou: z.string().max(1000).optional(),
}).strict().refine((r) => !['completed', 'failed', 'stopped'].includes(r.state) || !!r.report?.trim(), 'A terminal report needs its findings.');

export async function supervisorPrompt({ id, title, objective, instructions, mode = 'basic' }, reportFile, suppliedSkill) {
  const source = fileURLToPath(new URL('./bundled-plugins/orca/skills/roamie-supervisor/SKILL.md', import.meta.url));
  const allowed = checkRead(source, os.homedir());
  if (allowed.level === BLOCK) throw new Error(allowed.reason);
  const skill = suppliedSkill ?? await fs.readFile(source, 'utf8');
  return `You are an independent supervisor created by Roamie for the user's request. Your title is ${JSON.stringify(title)}.
Mode: ${mode}. Follow the bundled roamie-supervisor skill below in this mode.
Objective: ${objective}
Instructions and authorized scope, generated by Roamie from the user's request:
${instructions}

<supervisor-skill>
${skill}
</supervisor-skill>

Roamie displays your progress in a READ-ONLY overlay. Handle permitted coordination through tools; never send the user to task pickers, forms or assignment menus. Maintain this ONE local report file: ${JSON.stringify(reportFile)}
Write it before dispatching, whenever the state materially changes, before ending a turn to wait, and when finished. Write a complete JSON object atomically (temporary sibling then rename), using this output protocol:
{"supervisorId":${JSON.stringify(id)},"revision":1,"state":"working","progress":"Your current progress in plain words","report":"Your findings or final brief in your own words","needsYou":"Only if the user must answer"}
Increment revision on every write. state is working, waiting (needs the user), paused (user requested a pause), stopped (user requested a stop), completed, or failed. A completed/failed/stopped report must include a SHORT brief: usually 2–3 sentences, 40–80 words, outcome first with any important limitation or next action. Detailed evidence belongs in project files. A stop request is not proof a worker stopped: verify actual termination or state exactly what continues. Label reported vs independently checked evidence. No other process needs a worker_done report from you; your own workers still use the Orca worker lifecycle. Keep this file under 64 KiB. Do not modify Roamies' state.json or owner.lock.
Begin by recording progress, then carry out the objective.`;
}
export function makeBrief(record, observation, evidence) {
  const result = clip(observation.reportedResult?.trim() || 'No result details were available.', 240);
  const warning = evidence.warnings?.length ? ` ${clip(evidence.warnings[0], 100)}` : '';
  return `The task reported ${observation.outcome === 'succeeded' ? 'success' : observation.outcome === 'failed' ? 'failure' : observation.outcome}. ${result}\nThese results are not independently verified.${warning}`;
}

export function createSupervisors({ orca, root = supervisorsRoot(), changed = () => {}, open = () => {},
  allowDispatch = () => false, pluginCapabilities, supervisorSkill, write = writeJson, now = Date.now, intervalMs = 15000, isAlive = (pid) => { try { process.kill(pid, 0); return true; } catch (e) { return e.code !== 'ESRCH'; } } }) {
  const stateFile = path.join(root, 'state.json'), lockFile = path.join(root, 'owner.lock');
  let records = [], rules = interruptionRules(), error = null, closed = false, chain = Promise.resolve(), ownsLock = false;
  let lockToken, timer;
  const due = new Map(), failures = new Map();
  function guard(file) {
    const v = checkSupervisorStorage(file, root);
    if (v.level === BLOCK) throw new Error(v.reason);
  }
  const ready = (async () => {
    guard(stateFile); guard(lockFile);
    await fs.mkdir(root, { recursive: true, mode: 0o700 });
    try {
      const owner = JSON.parse(await fs.readFile(lockFile, 'utf8'));
      if (!Number.isInteger(owner.pid) || owner.pid < 1 || isAlive(owner.pid)) throw new Error('Another supervisor runtime owns this data folder.');
      await fs.unlink(lockFile); // Shell single-instance/replacement serializes startup; live owners are never evicted.
    } catch (e) { if (e.code !== 'ENOENT') throw e; }
    lockToken = randomUUID();
    await fs.writeFile(lockFile, JSON.stringify({ pid: process.pid, token: lockToken }), { flag: 'wx', mode: 0o600 });
    ownsLock = true;
    try {
      if ((await fs.stat(stateFile)).size > 8 << 20) throw new Error('Supervisor state is too large.');
      const data = JSON.parse(await fs.readFile(stateFile, 'utf8'));
      if (data.version !== 1 || !Array.isArray(data.supervisors) || data.supervisors.length > 100) throw new Error('Unsupported supervisor state.');
      rules = interruptionRules(data.interruptions);
      for (const r of data.supervisors) {
        if (!ID.test(r.id) || !['dispatching', 'working', 'watching', 'paused', 'needs_attention', 'completed', 'stopped'].includes(r.state)) throw new Error('Invalid supervisor state.');
        if (r.kind === 'coordinator') {
          orcaSupervisorArgs(r.launch.request);
          if (r.mode != null && !['basic', 'advanced'].includes(r.mode)) throw new Error('Invalid supervisor mode.');
        }
        else {
          orcaReadArgs('tasks', { runId: r.target?.runId });
          orcaReadArgs('worker', { dispatchId: r.target?.dispatchId });
          if (!/^task_[a-z0-9]{1,64}$/.test(r.target?.taskId)) throw new Error('Invalid saved task identity.');
        }
      }
      records = data.supervisors.map((r) => ({ ...r, mode: r.mode ?? (r.kind === 'coordinator' ? 'advanced' : 'basic'), connection: 'unknown',
        ...(r.state === 'dispatching' ? { state: 'needs_attention' } : {}),
        notice: r.state === 'dispatching' ? 'Launch was interrupted. Work may have started; no duplicate was launched.' : ['working', 'watching'].includes(r.state) ? 'Monitoring resumed after a gap; reconnecting to Orca.' : r.notice }));
    } catch (e) { if (e.code !== 'ENOENT') throw e; }
  })().catch((e) => { error = e.message; changed(); });
  const serial = (fn) => {
    const work = chain.then(async () => { await ready; if (closed) throw new Error('Supervisor runtime is closed.'); if (error) throw new Error(error); return fn(); });
    chain = work.catch(() => {}); return work;
  };
  async function commit(next, nextRules = rules) {
    guard(stateFile);
    await write(stateFile, { version: 1, supervisors: next, interruptions: nextRules }, { strict: true });
    records = next; rules = nextRules; changed();
  }
  const replace = (record) => commit(records.map((r) => r.id === record.id ? record : r));
  const find = (id) => { if (!ID.test(id)) throw new Error('Invalid supervisor ID.'); const r = records.find((r) => r.id === id); if (!r) throw new Error('Supervisor not found.'); return r; };
  const publicRecord = (r) => { const copy = structuredClone(r); if (copy.launch) delete copy.launch.request; return copy; };
  const snapshot = () => ({ error, supervisors: records.map(publicRecord), interruptions: { ...rules }, monitoring: 'Work continues in Orca when this card is closed.' });
  const reportFile = (id) => path.join(root, `${id}.report.json`);
  async function observeCoordinator(r) {
    const file = reportFile(r.id); guard(file);
    let raw;
    try {
      if ((await fs.stat(file)).size > 65536) throw new Error('Supervisor report exceeds 64 KiB.');
      raw = await fs.readFile(file, 'utf8');
    } catch (e) {
      if (e.code === 'ENOENT') return;
      throw e;
    }
    const report = coordinatorReport.parse(JSON.parse(raw.replace(/^\uFEFF/, '')));
    if (report.supervisorId !== r.id) throw new Error('Supervisor report identity changed.');
    if (report.revision <= (r.revision ?? 0)) return;
    const terminal = ['completed', 'failed', 'stopped'].includes(report.state);
    const question = report.state === 'waiting' ? report.needsYou || report.progress : null;
    await replace({ ...r, state: report.state === 'stopped' ? 'stopped' : terminal ? 'completed' : report.state === 'waiting' ? 'needs_attention' : report.state === 'paused' ? 'paused' : 'working',
      revision: report.revision, lastCheckedAt: now(), connection: 'reported', notice: report.progress,
      question, questionRevision: question ? r.question === question ? r.questionRevision ?? r.revision : report.revision : null,
      observation: { status: report.state, outcome: terminal ? report.state === 'completed' ? 'succeeded' : report.state === 'stopped' ? 'cancelled' : 'failed' : null, observedAt: now() },
      ...(terminal ? { brief: report.report, result: { id: `${r.id}:${report.revision}`, createdAt: now(), read: false, presented: false } } : {}) });
  }
  async function complete(r) {
    let evidence;
    try { evidence = await orca.evidence(r.target.dispatchId); }
    catch (e) { evidence = { text: '', limited: true, warnings: [clip(e.message, 300)] }; }
    const brief = makeBrief(r, r.observation, evidence);
    await replace({ ...r, state: 'completed', brief, briefError: null,
      result: { id: `${r.id}:${r.target.dispatchId}`, createdAt: now(), read: false, presented: false }, notice: 'Brief ready.' });
  }
  async function observe(r) {
    try {
      if (r.observation?.outcome) { await complete(r); return; }
      const o = await orca.observe(r.target);
      const binding = { runtime: o.runtime, incarnation: o.incarnation, workspace: o.workspace, dispatches: o.dispatches };
      if (o.dispatches.length !== 1 || r.binding && JSON.stringify(binding) !== JSON.stringify(r.binding)) {
        await replace({ ...r, state: 'needs_attention', connection: 'changed', notice: 'Orca runtime or dispatch identity changed. Inspect the Task before resuming.', lastCheckedAt: now() });
        return;
      }
      const next = { ...r, binding, observation: o, connection: 'connected', lastCheckedAt: now(), notice: o.status === 'completed' && !o.outcome ? 'Task is completed but its outcome is unavailable; waiting for evidence.' : '' };
      await replace(next); // Terminal evidence is durable before result publication.
      failures.delete(r.id);
      if (o.outcome) await complete(next);
    } catch (e) {
      const count = (failures.get(r.id) ?? 0) + 1;
      failures.set(r.id, count);
      // Preserve a terminal observation if brief persistence failed, so retry needn't re-run external work.
      const latest = find(r.id);
      await replace({ ...latest, connection: 'unavailable', notice: clip(e.message, 400), briefError: latest.observation?.outcome ? clip(e.message, 400) : null, lastCheckedAt: now() });
    } finally {
      due.set(r.id, now() + Math.min(300000, intervalMs * 2 ** Math.min(failures.get(r.id) ?? 0, 5)));
    }
  }
  function tick() {
    return serial(async () => {
      for (const r of [...records]) {
        if (r.kind === 'coordinator' && ['working', 'dispatching', 'paused', 'needs_attention'].includes(r.state)) {
          try { await observeCoordinator(r); }
          catch (e) { await replace({ ...r, connection: 'unavailable', notice: `Supervisor report unavailable: ${clip(e.message, 300)}` }); }
        } else if (r.state === 'watching' && (due.get(r.id) ?? 0) <= now()) await observe(r);
      }
    }).catch((e) => { error = `Supervisor storage/runtime error: ${e.message}`; changed(); });
  }
  function launch({ workspace, agent, model, title, objective, instructions, mode = 'basic', plugins: selectedPlugins = [], needsPluginMcp = false }) {
    if (!allowDispatch()) throw new Error('Orca dispatch requires Allow File Edits & Commands. Read-only status and watches still work without it.');
    mode ??= 'basic'; // Provider schemas may encode an omitted optional field as null.
    if (!['basic', 'advanced'].includes(mode)) throw new Error('Choose basic or advanced supervisor mode.');
    if (![title, objective, instructions].every((s) => typeof s === 'string' && s.trim()) || title.length > 120 || objective.length > 2000 || instructions.length > 12000) throw new Error('Generate a title, objective and bounded instructions from the user request.');
    return serial(async () => {
      if (!allowDispatch()) throw new Error('Orca dispatch is now disabled.');
      if (selectedPlugins.length || needsPluginMcp) {
        if (!pluginCapabilities) throw new Error('Supervisor plugin capabilities are unavailable.');
        const material = await pluginCapabilities(selectedPlugins, needsPluginMcp);
        instructions += `\n\n${material}`;
      }
      const dispatchKey = createHash('sha256').update(JSON.stringify({ workspace, agent, model, title, objective, instructions, mode })).digest('hex');
      const legacyKey = createHash('sha256').update(JSON.stringify({ workspace, agent, model, title, objective, instructions })).digest('hex');
      const existing = records.find((r) => (r.dispatchKey === dispatchKey || r.kind === 'coordinator' && (r.mode ?? 'advanced') === mode && r.dispatchKey === legacyKey) && !['completed', 'stopped'].includes(r.state));
      if (existing) return publicRecord(existing);
      if (records.length >= 100 || records.filter((r) => r.kind === 'coordinator' ? !['completed', 'stopped'].includes(r.state) : r.state === 'watching').length >= 10) throw new Error('Supervisor capacity reached.');
      const id = `s_${randomUUID()}`, r = { id, kind: 'coordinator', mode, dispatchKey, title, objective, instructions, state: 'dispatching', createdAt: now(), lastCheckedAt: null,
        connection: 'starting', revision: 0, observation: null, brief: null, result: null, notice: 'Starting an independent model supervisor in Orca.' };
      guard(reportFile(id));
      const request = { workspace, agent, ...(model ? { model } : {}), prompt: await supervisorPrompt(r, reportFile(id), await supervisorSkill?.()) };
      orcaSupervisorArgs(request);
      r.launch = { request, receipt: null };
      await commit([...records, r]); // Retain intent before anything external can start.
      let receipt = null;
      try {
        receipt = await orca.launchSupervisor(request);
        const next = { ...r, state: 'working', connection: 'awaiting_report', launch: { request, receipt }, notice: 'Supervisor launched; waiting for its first progress report.' };
        await replace(next);
        return publicRecord(next);
      } catch (e) {
        const blocked = { ...r, state: 'needs_attention', connection: 'unknown', notice: clip(e.message, 500),
          launch: { request, receipt, operationId: receipt?.operationId ?? e.operationId ?? null, uncertain: !receipt } };
        await replace(blocked); // Never automatically repeat a possibly accepted launch.
        return publicRecord(blocked);
      }
    });
  }
  function message(id, text) {
    if (!allowDispatch()) throw new Error('Orca messages require Allow File Edits & Commands.');
    if (typeof text !== 'string' || !text.trim() || text.length > 10000) throw new Error('Provide a bounded instruction from the user.');
    return serial(async () => {
      if (!allowDispatch()) throw new Error('Orca messages are now disabled.');
      const r = find(id), handle = r.launch?.receipt?.handle;
      if (r.kind !== 'coordinator' || !handle) throw new Error('This supervisor has no confirmed live Orca agent to message.');
      if (['completed', 'stopped'].includes(r.state)) throw new Error('This supervisor has ended. Create a new supervisor for new work.');
      if (r.message?.state === 'uncertain' && r.message.text === text) throw new Error('That message has uncertain delivery. Inspect the supervisor in Orca before resending.');
      if (r.message?.state === 'accepted' && r.message.text === text && r.message.revision === r.revision) return { id, accepted: true, alreadyDelivered: true };
      const outgoing = { id: randomUUID(), text, at: now(), revision: r.revision, state: 'uncertain' };
      await replace({ ...r, message: outgoing }); // A crash cannot silently turn into a duplicate send.
      try {
        const receipt = await orca.messageSupervisor(handle, `Message from the user via Roamie: ${text}\nContinue to update your existing supervisor report file.`);
        await replace({ ...r, message: { ...outgoing, state: 'accepted', receipt }, notice: 'Instructions delivered to the supervisor.' });
        return { id, accepted: true };
      } catch (e) {
        await replace({ ...find(id), notice: clip(e.message, 500) });
        return { id, accepted: false, uncertain: true, error: clip(e.message, 500) };
      }
    });
  }
  async function create({ runId, taskId, dispatchId, title, objective }) {
    orcaReadArgs('tasks', { runId }); orcaReadArgs('worker', { dispatchId });
    if (!/^task_[a-z0-9]{1,64}$/.test(taskId) || !String(objective ?? '').trim()) throw new Error('Select a Task and describe the assignment.');
    return serial(async () => {
      if (records.filter((r) => r.state === 'watching').length >= 10 || records.length >= 100) throw new Error('Supervisor capacity reached.');
      const duplicate = records.find((r) => r.target?.dispatchId === dispatchId && !['stopped', 'completed'].includes(r.state));
      if (duplicate) return structuredClone(duplicate);
      const target = { runId, taskId, dispatchId };
      const o = await orca.observe(target);
      if (o.dispatches.length !== 1) throw new Error('This Task has multiple dispatches. Watching retries is not supported yet.');
      const r = { id: `s_${randomUUID()}`, mode: 'basic', title: clip(title || o.title || 'Orca supervisor', 120), objective: clip(objective, 2000), target,
        state: 'watching', createdAt: now(), connection: 'connected', lastCheckedAt: now(), observation: o,
        binding: { runtime: o.runtime, incarnation: o.incarnation, workspace: o.workspace, dispatches: o.dispatches }, brief: null, result: null, notice: '' };
      await commit([...records, r]); due.set(r.id, 0);
      return structuredClone(r);
    });
  }
  function action(id, action) {
    return serial(async () => {
      const r = find(id);
      if (action === 'read' || action === 'presented' || action === 'announced') {
        if (r.result) await replace({ ...r, result: { ...r.result, [action]: true, ...(action === 'read' ? { presented: true } : {}) } });
      } else if (action === 'question_announced') {
        await replace({ ...r, questionAnnouncedRevision: r.revision });
      } else if (['pause', 'resume', 'stop'].includes(action)) {
        if (r.kind === 'coordinator') throw new Error('This is a live Orca supervisor agent. Use message_supervisor to convey the user\'s request and wait for its report; observation controls cannot pause or stop its work.');
        if (r.state === 'completed' || r.state === 'stopped') throw new Error('This supervisor has ended.');
        await replace({ ...r, state: action === 'pause' ? 'paused' : action === 'stop' ? 'stopped' : 'watching',
          ...(action === 'resume' ? { binding: null, connection: 'unknown' } : {}), notice: action === 'stop' ? 'Observation stopped; the Orca worker was left running.' : '' });
        due.set(id, 0);
      } else throw new Error('Unsupported supervisor action.');
      return structuredClone(find(id));
    });
  }
  const rulePatch = z.object({ failures: z.enum(['immediate', 'quiet', 'off']).nullish(), questions: z.enum(['immediate', 'quiet', 'off']).nullish(), completions: z.enum(['immediate', 'quiet', 'off']).nullish(), snoozeMinutes: z.number().int().min(0).max(1440).nullish() }).strict();
  function setInterruptions(patch = {}) {
    const p = rulePatch.parse(patch);
    return serial(async () => {
      const next = { ...rules };
      for (const key of ['failures', 'questions', 'completions']) if (p[key] != null) next[key] = p[key];
      if (p.snoozeMinutes != null) next.snoozeUntil = p.snoozeMinutes ? now() + p.snoozeMinutes * 60000 : 0;
      if (JSON.stringify(next) !== JSON.stringify(rules)) await commit(records, next);
      return { ...rules, scope: 'Automatic supervisor and background-agent announcements. Progress stays quiet. Reminders and requested replies are separate.' };
    });
  }
  function claimNotification(id, key) {
    return serial(async () => {
      const r = find(id), event = supervisorInterruption(r);
      if (!event || event.key !== key) return false;
      const prior = r.notification?.key === key ? r.notification : null;
      if (prior?.nextAttemptAt > now()) return false;
      const attempts = (prior?.attempts ?? 0) + 1;
      await replace({ ...r, notification: { key, attempts, attemptedAt: now(), nextAttemptAt: now() + Math.min(300000, 30000 * 2 ** Math.min(attempts - 1, 4)) } });
      return true;
    });
  }
  function notified(id, key) {
    return serial(async () => {
      const r = find(id), event = supervisorInterruption(r);
      if (!event || event.key !== key || r.notification?.key !== key) return false;
      await replace({ ...r, notification: { ...r.notification, deliveredAt: now() },
        ...(r.result?.id === key ? { result: { ...r.result, announced: true } } : r.question ? { questionAnnouncedRevision: r.revision } : {}) });
      return true;
    });
  }
  async function close() {
    clearInterval(timer); await ready; await chain; closed = true;
    if (ownsLock) {
      guard(lockFile);
      const owner = JSON.parse(await fs.readFile(lockFile, 'utf8'));
      if (owner.token === lockToken) await fs.unlink(lockFile);
      ownsLock = false;
    }
  }
  if (intervalMs > 0) { timer = setInterval(() => { if (!closed) void tick(); }, intervalMs); timer.unref?.(); }
  return { ready, snapshot, create, launch, message, action, tick, close, setInterruptions, claimNotification, notified, open, get: (id) => publicRecord(find(id)) };
}
